# 物理常数定义
# ------------------------------------------------------------

import numpy as np

# 真空光速 c0
c0 = 299792458.0

# 真空磁导率 μ0
mu0 = 4e-7 * np.pi

# 真空介电常数 ε0
eps0 = 1.0 / (mu0 * c0**2)

# 真空波阻抗 η0
eta0 = np.sqrt(mu0 / eps0)